#!/usr/bin/env python3
"""Summarise results/processed/layers_profile.json -> results/processed/summary.md
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "results", "processed")
R = json.load(open(os.path.join(P, "layers_profile.json")))
META = {e["name"]: e for e in json.load(open(os.path.join(ROOT, "gen", "layers.json")))}
LAY = list(META)
CFG = ["b0", "b1", "x0", "x1", "x2"]
NAME = {"b0": "B0", "b1": "B1", "x0": "X0", "x1": "X1", "x2": "X2"}


def cell(c, l):
    return R["%s/%s" % (c, l)]


def mixsum(c, layers):
    mix = {}
    for l in layers:
        for k, v in cell(c, l)["mix"].items():
            mix[k] = mix.get(k, 0) + v
    return mix


out = []
w = out.append
tot = {c: sum(cell(c, l)["total"] for l in LAY) for c in CFG}
MAC = sum(META[l]["macs"] for l in LAY)
w("# Results summary (generated by scripts/summarize.py)\n")
w("ResNet-18 W8A8, %d layers (%d CONV_2D + %d FC), %.1f MMAC = 100%% of the network's "
  "MACs. Dynamic instructions of the kernel only (Spike PC histogram, validated "
  "against the full -l trace). Every cell is bit-exact vs the TFLite interpreter.\n"
  % (len(LAY), len(LAY) - 1, 1, MAC / 1e6))

w("## Whole network (sum of all layers)\n")
w("| Config | Description | Dyn. insns | MAC/insn | ld+st/MAC | vs B0 | vs B1 | step gain |")
w("|---|---|---:|---:|---:|---:|---:|---:|")
desc = {"b0": "baseline RV64IMC", "b1": "software-optimised (2-ch tile, 4x unroll)",
        "x0": "B1 loop + qmac8, software requant", "x1": "X0 + qreq",
        "x2": "X1 + ldpi (post-increment load)"}
prev = None
for c in CFG:
    mix = mixsum(c, LAY)
    ls = mix.get("load", 0) + mix.get("store", 0) + mix.get("ldpi", 0)
    step = "" if prev is None else "%.2fx" % (tot[prev] / tot[c])
    w("| %s | %s | %d | %.3f | %.3f | %.2fx | %.2fx | %s |" %
      (NAME[c], desc[c], tot[c], MAC / tot[c], ls / MAC, tot["b0"] / tot[c],
       tot["b1"] / tot[c], step))
    prev = c
w("")
w("Incremental: **qmac8** (B1->X0) = %.2fx, **qreq** (X0->X1) = %.2fx, "
  "both (B1->X1) = %.2fx, vs naive baseline (B0->X1) = %.2fx.\n"
  % (tot["b1"] / tot["x0"], tot["x0"] / tot["x1"], tot["b1"] / tot["x1"],
     tot["b0"] / tot["x1"]))
w("Extension X2: **ldpi** (X1->X2) = %.2fx, both-to-end B1->X2 = %.2fx, B0->X2 = %.2fx.\n"
  % (tot["x1"] / tot["x2"], tot["b1"] / tot["x2"], tot["b0"] / tot["x2"]))

w("## Instruction mix (whole network)\n")
w("| Config | load | store | ALU | multiply | branch+jump | qmac8 | qreq | ldpi |")
w("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for c in CFG:
    m = mixsum(c, LAY)
    t = sum(m.values())
    pc = lambda k: "%.1f%%" % (100.0 * m.get(k, 0) / t)
    w("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" %
      (NAME[c], pc("load"), pc("store"), pc("alu"), pc("multiply"),
       "%.1f%%" % (100.0 * (m.get("branch", 0) + m.get("jump", 0)) / t),
       pc("qmac8"), "%.2f%%" % (100.0 * m.get("qreq", 0) / t), pc("ldpi")))
w("")

w("## Per layer\n")
w("| layer | M x N x K | MACs | B0 | B1 | X0 | X1 | X2 | B1/X1 | X1/X2 | B1/X2 |")
w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for l in LAY:
    e = META[l]
    t = {c: cell(c, l)["total"] for c in CFG}
    w("| %s | %dx%dx%d | %d | %d | %d | %d | %d | %d | %.2fx | %.2fx | %.2fx |" %
      (l, e["M"], e["N"], e["K"], e["macs"], t["b0"], t["b1"], t["x0"], t["x1"],
       t["x2"], t["b1"] / t["x1"], t["x1"] / t["x2"], t["b1"] / t["x2"]))
w("")

w("## Requantization cost (instructions per output element)\n")
w("| layer | K | X0 (sw requant) | X1 (qreq) | saved by qreq | saved / X0 |")
w("|---|---:|---:|---:|---:|---:|")
for l in LAY:
    o = cell("x0", l)["outputs"]
    a, b = cell("x0", l)["total"] / o, cell("x1", l)["total"] / o
    w("| %s | %d | %.1f | %.1f | %.1f | %.1f%% |" % (l, META[l]["K"], a, b, a - b,
                                                   100 * (a - b) / a))
w("")

w("## Targets from the project brief\n")
big = max(LAY, key=lambda l: META[l]["macs"])
red = [(l, cell("b1", l)["total"] / cell("x1", l)["total"]) for l in LAY]
w("- >=2x dynamic-instruction reduction on a major GEMM/FC kernel: "
  "min over layers B1->X1 = %.2fx (%s), max = %.2fx (%s); "
  "vs B0: min %.2fx, max %.2fx. **Met** for every layer."
  % (min(r for _, r in red), min(red, key=lambda x: x[1])[0],
     max(r for _, r in red), max(red, key=lambda x: x[1])[0],
     min(cell("b0", l)["total"] / cell("x1", l)["total"] for l in LAY),
     max(cell("b0", l)["total"] / cell("x1", l)["total"] for l in LAY)))
w("- End-to-end >=1.5x: this table is an *instruction-count* ratio of the conv/FC "
  "kernels only (%.2fx vs B1, %.2fx vs B0). The whole chained model, including "
  "pad/pool/add/transpose/im2col, is in model_summary.md (scripts/summarize_model.py). "
  "Neither is a cycle or wall-clock speedup."
  % (tot["b1"] / tot["x1"], tot["b0"] / tot["x1"]))
open(os.path.join(P, "summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
