"""Emit gen/layers.S (.incbin of the exported blobs) and gen/layers.h."""
import os

SFX = ["a", "w", "bias", "mult", "shift", "packed", "y"]
CT = {"a": "int8_t", "w": "int8_t", "y": "int8_t", "bias": "int32_t",
      "mult": "int32_t", "shift": "int8_t", "packed": "uint64_t"}


def emit(meta, out):
    with open(os.path.join(out, "layers.S"), "w") as f:
        f.write("/* generated by scripts/export_layers.py - do not edit */\n"
                "    .section .rodata\n    .balign 8\n")
        for e in meta:
            for s in SFX:
                f.write(f"    .globl L_{e['name']}_{s}\nL_{e['name']}_{s}:\n"
                        f"    .incbin \"gen/{e['name']}_{s}.bin\"\n    .balign 8\n")
    with open(os.path.join(out, "layers.h"), "w") as f:
        f.write("/* generated by scripts/export_layers.py - do not edit */\n"
                "#ifndef LAYERS_H\n#define LAYERS_H\n#include \"layer_t.h\"\n\n")
        for e in meta:
            for s in SFX:
                f.write(f"extern const {CT[s]} L_{e['name']}_{s}[];\n")
        f.write("\nstatic const layer_t LAYERS[] = {\n")
        for e in meta:
            n = e["name"]
            f.write('    {"%s", %d,%d,%d,%d, %d,%d,%d,\n'
                    "     L_%s_a, L_%s_w, L_%s_y, L_%s_bias, L_%s_mult, L_%s_shift, L_%s_packed},\n"
                    % (n, e["M"], e["N"], e["K"], e["Kp"], e["out_zp"],
                       e["act_min"], e["act_max"], n, n, n, n, n, n, n))
        f.write("};\n#define NUM_LAYERS ((int)(sizeof(LAYERS)/sizeof(LAYERS[0])))\n#endif\n")


