#!/usr/bin/env python3
"""Generate golden vectors for qreq -> gen/qreq_vectors.h  (numpy only).

"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tflq  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "gen", "qreq_vectors.h")
rng = np.random.default_rng(20251015)


def expect(acc, mult, shift, zp, amin, amax):
    a = np.array([[acc]], np.int64)
    y = tflq.mulq_channels(a, [mult], [shift])[0, 0] + zp
    return int(min(max(y, amin), amax))


cases = []
# directed: rounding ties (+/-), zero, saturation, fused-activation clamps
for acc in (0, 1, -1, 2, -2, 3, -3, 127, -128, 129, -129, 1000, -1000,
            65535, -65536, 2**20, -2**20, 2**24, -2**24):
    for mult in (1 << 30, (1 << 30) + 1, (1 << 31) - 1, 1717986918):
        for shift in (-14, -9, -5, -1, 0, 1):
            if shift > 0 and abs(acc) << shift >= 2**31:
                continue
            for zp, amin, amax in ((0, -128, 127), (-128, -128, 127),
                                   (-26, -26, 127), (-128, -128, -128 + 255 // 6 * 1)):
                cases.append((acc, mult, shift, zp, amin, amax))
# random
for _ in range(3000):
    shift = int(rng.integers(-14, 2))
    lim = (2**31 >> max(shift, 0)) - 1
    acc = int(rng.integers(-min(lim, 600000), min(lim, 600000) + 1))
    mult = int(rng.integers(1 << 30, (1 << 31) - 1))
    zp = int(rng.integers(-128, 128))
    amin = int(rng.choice([-128, zp if zp > -128 else -128]))
    amax = int(rng.choice([127, min(127, zp + 40)]))
    if amin > amax:
        amin, amax = -128, 127
    cases.append((acc, mult, shift, zp, amin, amax))

with open(OUT, "w") as f:
    f.write("/* generated by scripts/gen_qreq_vectors.py - do not edit */\n"
            "#ifndef QREQ_VECTORS_H\n#define QREQ_VECTORS_H\n#include <stdint.h>\n"
            "typedef struct { int32_t acc, mult; int8_t shift, zp, amin, amax, exp; } qreq_vec_t;\n"
            "static const qreq_vec_t QREQ_VECS[] = {\n")
    for c in cases:
        f.write("  {%d,%d,%d,%d,%d,%d,%d},\n" % (*c, expect(*c)))
    f.write("};\n#define NUM_QREQ_VECS ((int)(sizeof(QREQ_VECS)/sizeof(QREQ_VECS[0])))\n#endif\n")
print("wrote %d vectors -> %s" % (len(cases), OUT))
