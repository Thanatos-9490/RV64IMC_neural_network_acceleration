#!/usr/bin/env python3
"""Whole-network (37 ops) instruction summary -> results/processed/model_summary.md

Input : results/processed/model_profile.json   (scripts/profile_model.py)
        results/processed/layers_profile.json  (scripts/profile_pc.py, used as a
                                                cross-check of the GEMM part)
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "results", "processed")
M = json.load(open(os.path.join(P, "model_profile.json")))
L = json.load(open(os.path.join(P, "layers_profile.json")))
CFG = [c for c in ("b0", "b1", "x0", "x1", "x1t", "x2", "x2t") if c in M]
NAME = {"b0": "B0", "b1": "B1", "x0": "X0", "x1": "X1", "x1t": "X1T", "x2": "X2", "x2t": "X2T"}
GR = ["gemm", "im2col", "pad", "transpose", "maxpool", "add", "avgpool", "dispatch"]
MACS = 1814073344

out = []
w = out.append
tot = {c: sum(sum(m.values()) for m in M[c]["groups"].values()) for c in CFG}
gem = {c: sum(M[c]["groups"]["gemm"].values()) for c in CFG}
non = {c: tot[c] - gem[c] for c in CFG}

w("# Full-network inference summary (generated by scripts/summarize_model.py)\n")
w("ResNet-18 W8A8, **all 37 graph ops chained** (TRANSPOSE, 5 PAD, 20 CONV_2D, "
  "MAX_POOL, 8 ADD, AVG_POOL, FC), one image, bit-exact vs TFLite per op and on the "
  "logits. Dynamic instructions of the inference only (checksum/compare code excluded). "
  "Instruction counts, not cycles.\n")

w("## Whole model\n")
w("| Config | total insns | GEMM (conv+FC) | non-GEMM ops | non-GEMM share | MAC/insn | vs B0 | vs B1 |")
w("|---|---:|---:|---:|---:|---:|---:|---:|")
for c in CFG:
    w("| %s | %d | %d | %d | %.1f%% | %.3f | %.2fx | %.2fx |" %
      (NAME[c], tot[c], gem[c], non[c], 100.0 * non[c] / tot[c], MACS / tot[c],
       tot["b0"] / tot[c], tot["b1"] / tot[c]))
w("")
w("End-to-end B1->X1 = **%.2fx** (GEMM-only B1->X1 = %.2fx): the non-GEMM operators "
  "are untouched by the extension, so Amdahl's law pulls the whole-model number "
  "below the kernel number." % (tot["b1"] / tot["x1"], gem["b1"] / gem["x1"]))
w("")

w("## Contribution of each operator class (share of total instructions)\n")
w("| operator | " + " | ".join(NAME[c] for c in CFG) + " |")
w("|---|" + "---:|" * len(CFG))
for g in GR:
    w("| %s | " % g + " | ".join(
        "%d (%.2f%%)" % (sum(M[c]["groups"][g].values()),
                         100.0 * sum(M[c]["groups"][g].values()) / tot[c]) for c in CFG) + " |")
w("")

w("## Instruction mix of the whole model\n")
w("| Config | load | store | ALU | multiply | branch+jump | qmac8 | qreq | ldpi |")
w("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for c in CFG:
    mix = {}
    for m in M[c]["groups"].values():
        for k, v in m.items():
            mix[k] = mix.get(k, 0) + v
    pc = lambda k: "%.1f%%" % (100.0 * mix.get(k, 0) / tot[c])
    w("| %s | %s | %s | %s | %s | %.1f%% | %s | %s | %s |" %
      (NAME[c], pc("load"), pc("store"), pc("alu"), pc("multiply"),
       100.0 * (mix.get("branch", 0) + mix.get("jump", 0)) / tot[c], pc("qmac8"), pc("qreq"), pc("ldpi")))
w("")

w("## Cross-check: GEMM part of the chained run vs the stand-alone layer profile\n")
w("| Config | chained GEMM insns (1 image) | sum of 21 layers (layers_profile.json) | diff |")
w("|---|---:|---:|---:|")
for c in CFG:
    if c in ("x1t", "x2t"):
        continue
    s = sum(v["total"] for k, v in L.items() if k.startswith(c + "/"))
    w("| %s | %d | %d | %+d |" % (NAME[c], gem[c], s, gem[c] - s))
w("")
w("The two profiles use the same `run_layer`/`gemm_*` source, so the GEMM part of the "
  "chained run must equal the sum of the stand-alone layers up to a few instructions of "
  "function prologue/register allocation (here at most 21 of ~10^9-10^10). A large diff "
  "would mean the chained run executes different kernel code than the verified layers.\n")

if "x2" in M:
    w("## X2 (ldpi) and the T variants\n")
    w("X1->X2 = %.3fx, X1T->X2T = %.3fx (whole model, same loop order; only the pointer "
      "bumps are fused into the loads).  X1->X1T = %.4fx (loop order only; its benefit is "
      "in the data cache, see cache_summary.md)." %
      (tot["x1"] / tot["x2"], tot["x1t"] / tot["x2t"], tot["x1"] / tot["x1t"]))
open(os.path.join(P, "model_summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
