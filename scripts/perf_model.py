#!/usr/bin/env python3
"""Analytical performance model: ISA improvement vs microarchitectural improvement.

"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "results", "processed")
MP = json.load(open(os.path.join(P, "model_profile.json")))
CS = json.load(open(os.path.join(P, "cache_sweep.json")))
LAYERS = json.load(open(os.path.join(ROOT, "gen", "layers.json")))
OUTPUTS = sum(e["M"] * e["N"] for e in LAYERS)
MACS = sum(e["macs"] for e in LAYERS)
CACHE = "16K-4w-64B-plru"
NAME = {"b0": "B0", "b1": "B1", "x0": "X0", "x1": "X1", "x1t": "X1T", "x2": "X2", "x2t": "X2T"}
# X0 was not simulated: it has the address stream of X1 (same loads, same order)
MISS_SRC = {"b1": "b1", "x0": "x1", "x1": "x1", "x1t": "x1t", "x2": "x2", "x2t": "x2t"}


def counts(cfg):
    m = {}
    for g in MP[cfg]["groups"].values():
        for k, v in g.items():
            m[k] = m.get(k, 0) + v
    return m


def misses(cfg):
    src = MISS_SRC.get(cfg)
    if src is None or src not in CS["runs"]:
        return None
    return sum(v[2] + v[3] for v in CS["runs"][src][CACHE].values())


def cycles(cfg, q_mac=1, q_req=2, br_extra=2, lu=1, lat=10, with_miss=True):
    n = counts(cfg)
    ld = n.get("load", 0) + n.get("ldpi", 0)
    br = n.get("branch", 0) + n.get("jump", 0)
    c = (n.get("alu", 0) + ld + n.get("store", 0) + n.get("multiply", 0)
         + n.get("qmac8", 0) * q_mac + n.get("qreq", 0) * q_req + br)
    c += 0.9 * br * br_extra + 0.5 * ld * lu
    if with_miss and misses(cfg) is not None:
        c += misses(cfg) * (lat + 8)
    return c


def main():
    cfgs = [c for c in ("b0", "b1", "x0", "x1", "x1t", "x2", "x2t") if c in MP]
    n = {c: sum(counts(c).values()) for c in cfgs}
    o = []
    w = o.append
    w("# Performance model (generated by scripts/perf_model.py)\n")
    w("Measured inputs: dynamic instructions per class (Spike), D-cache misses (16 KB 4-way "
      "64 B PLRU).  **Every cycle value below is a model with stated assumptions, not a "
      "measurement** (see the docstring of scripts/perf_model.py).\n")

    w("## 1. ISA improvement (instruction count, CPI = 1)\n")
    w("| Config | insns | vs B0 | vs B1 | step gain | MAC/insn |")
    w("|---|---:|---:|---:|---:|---:|")
    chain = [c for c in ("b0", "b1", "x0", "x1", "x2") if c in n]
    for c in cfgs:
        step = ""
        if c in chain and chain.index(c) > 0:
            step = "%.2fx" % (n[chain[chain.index(c) - 1]] / n[c])
        w("| %s | %d | %.2fx | %.2fx | %s | %.3f |" %
          (NAME[c], n[c], n["b0"] / n[c], n["b1"] / n[c], step, MACS / n[c]))
    w("")

    w("## 2. ISA + microarchitecture (cycle model, default assumptions)\n")
    w("qmac8 = 1 cycle, qreq = 2, taken-branch penalty 2, load-use 1 (half of the loads), "
      "miss = LAT + 8 with LAT = 10.\n")
    w("| Config | model cycles (G) | CPI | speedup vs B1 | ISA-only speedup | cycle/ISA |")
    w("|---|---:|---:|---:|---:|---:|")
    cb = cycles("b1")
    for c in cfgs:
        cy = cycles(c)
        isa, sp = n["b1"] / n[c], cb / cy
        w("| %s | %.3f | %.3f | %.2fx | %.2fx | %.2f |" % (NAME[c], cy / 1e9, cy / n[c], sp, isa, sp / isa))
    w("")
    w("cycle/ISA < 1: the pipeline and memory system eat part of the instruction-count gain "
      "(branch penalty, load-use, qmac8/qreq latency, cache misses).\n")

    w("## 3. Sensitivity of B1 -> X2T to the unknown latencies\n")
    w("| qmac8 latency | qreq latency | LAT 10 + misses | LAT 40 + misses | no misses |")
    w("|---:|---:|---:|---:|---:|")
    for qm in (1, 2, 3, 4):
        for qr in (2, 4):
            row = [qm, qr]
            for lat, wm in ((10, True), (40, True), (10, False)):
                row.append("%.2fx" % (cycles("b1", lat=lat, with_miss=wm) /
                                       cycles("x2t", q_mac=qm, q_req=qr, lat=lat, with_miss=wm)))
            w("| %d | %d | %s | %s | %s |" % tuple(row))
    w("")
    w("The qmac8 row is the quantity the RTL milestone has to measure.  The model charges the "
      "latency per instruction (it assumes the two independent accumulators of the inner "
      "loop hide nothing); a pipelined qmac8 with dependent-accumulate forwarding would "
      "cost 1 cycle per instruction regardless of its depth.\n")

    w("## 4. Per output element (brief section 3: instructions/output, cycles/output)\n")
    w("GEMM part only, %d output elements in the 21 layers.\n" % OUTPUTS)
    w("| Config | GEMM insns / output | model cycles / output (whole model) |")
    w("|---|---:|---:|")
    for c in cfgs:
        g = sum(MP[c]["groups"]["gemm"].values())
        w("| %s | %.1f | %.1f |" % (NAME[c], g / OUTPUTS, cycles(c) / OUTPUTS))
    w("")
    open(os.path.join(P, "perf_model.md"), "w").write("\n".join(o) + "\n")
    print("\n".join(o))


if __name__ == "__main__":
    main()
