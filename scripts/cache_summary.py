#!/usr/bin/env python3
"""Cache design-space tables + figures -> results/processed/cache_summary.md,
results/figures/cache_*.png.   Input: cache_sweep.json, model_profile.json.
"""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt          # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "results", "processed")
FIG = os.path.join(ROOT, "results", "figures")
os.makedirs(FIG, exist_ok=True)
D = json.load(open(os.path.join(P, "cache_sweep.json")))
MP = json.load(open(os.path.join(P, "model_profile.json")))
META = json.load(open(os.path.join(ROOT, "gen", "model.json")))
CFGS = {n: tuple(v) for n, v in D["configs"].items()}   # name -> (size, ways, line, policy)
RUNS = D["runs"]
KB = 1024
NAME = {"b1": "B1", "x1": "X1", "x1t": "X1T"}
BASE = "16K-4w-64B-plru"                      # CV-Wally's default D-cache


def insns(c):
    return sum(sum(m.values()) for m in MP[c]["groups"].values())


def tot(run, name, phases=None):
    """[rd, wr, rdm, wrm, wb] summed over the given phases (default all)."""
    t = [0] * 5
    for ph, v in RUNS[run][name].items():
        if phases is None or int(ph) in phases:
            t = [a + b for a, b in zip(t, v)]
    return t


def stats(run, name, phases=None):
    t = tot(run, name, phases)
    acc, miss = t[0] + t[1], t[2] + t[3]
    line = CFGS[name][2]
    return dict(acc=acc, miss=miss, rate=100.0 * miss / acc if acc else 0.0,
                wb=t[4], traffic=(miss + t[4]) * line)


def mpki(run, name):
    return 1000.0 * stats(run, name)["miss"] / insns(run)


def penalty(name, lat):
    return lat + CFGS[name][2] // 8


def cycles(run, name, lat=10):
    return insns(run) + stats(run, name)["miss"] * penalty(name, lat)


def gemm_phases():
    return {k for k, kind in enumerate(META["op_kinds"]) if kind in ("CONV_2D", "FULLY_CONNECTED")}


def table(rows, head):
    o = ["| " + " | ".join(head) + " |", "|" + "---:|" * len(head)]
    o += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return o


def main():
    o = []
    w = o.append
    G = gemm_phases()
    runs = [r for r in ('b1', 'x1', 'x1t') if r in RUNS]
    w("# Cache design exploration (generated by scripts/cache_summary.py)\n")
    w("Workload: chained ResNet-18 W8A8 inference, ONE image, every data load/store of "
      "the 37 ops (verification code excluded), cold cache at start, write-back + "
      "write-allocate. Instruction fetches are not modelled. Simulator validated "
      "against Spike `--dc` (identical counts, see EXPERIMENTS.md).\n")
    w("Workload instruction counts: " + ", ".join(
        "%s %.3f G" % (NAME[r], insns(r) / 1e9) for r in runs) + ".\n")

    def sweep(title, names, run):
        w("### %s  (%s)\n" % (title, NAME[run]))
        rows = []
        for n in names:
            s = stats(run, n)
            rows.append((n, "%.3f%%" % s["rate"], "%.1f" % mpki(run, n),
                         "%.1f MB" % (s["traffic"] / 1e6),
                         "%.3f" % (cycles(run, n) / insns(run)),
                         "%.3f" % (cycles(run, n, 40) / insns(run))))
        o.extend(table(rows, ("cache", "miss rate", "MPKI", "mem traffic",
                              "model CPI (LAT 10)", "model CPI (LAT 40)")))
        w("")

    by = lambda pred: [n for n in CFGS if pred(*CFGS[n])]
    for run in runs:
        sweep("Size", by(lambda s, a, l, p: a == 4 and l == 64 and p == 'plru'), run)
        sweep("Associativity (16 KB)", by(lambda s, a, l, p: s == 16 * KB and l == 64 and p == 'plru'), run)
        sweep("Line size (16 KB, 4-way)", by(lambda s, a, l, p: s == 16 * KB and a == 4 and p == 'plru'), run)
        sweep("Replacement policy (4-way, 64 B)", by(lambda s, a, l, p: a == 4 and l == 64 and s <= 32 * KB), run)

    # does the cache erase the ISA gain?  (model: cycles = insns + misses * P)
    w("## Does the cache erase the ISA gain? (instruction-count model + miss model)\n")
    w("Same program, same cache, B1 (scalar) vs X1 (qmac8+qreq) vs X1T (X1, cache-blocked). "
      "`ideal` = no misses = pure instruction ratio. Misses are nearly the same absolute number "
      "for B1 and X1 (the same bytes are touched), but X1 retires ~6.5x fewer instructions, so "
      "its misses per instruction (MPKI) are ~6.5x higher.\n")
    rows = []
    for name in ("4K-4w-64B-plru", BASE, "64K-4w-64B-plru"):
        if name not in CFGS or "b1" not in RUNS:
            continue
        for lat in (10, 40):
            cb = cycles("b1", name, lat)
            row = [name, lat, "%.3f" % (cb / insns("b1"))]
            for r in ("x1", "x1t"):
                if r in RUNS:
                    row += ["%.3f" % (cycles(r, name, lat) / insns(r)),
                            "%.2fx" % (cb / cycles(r, name, lat))]
            rows.append(row)
    o.extend(table(rows, ("cache", "LAT", "B1 CPI", "X1 CPI", "B1->X1", "X1T CPI", "B1->X1T")))
    w("")
    w("ideal (no misses): B1->X1 = %.2fx, B1->X1T = %.2fx.\n" %
      (insns("b1") / insns("x1"), insns("b1") / insns("x1t")))

    # policy spread = best - worst miss count at the same geometry
    w("## Workload sensitivity of the replacement policy\n")
    w("Spread = (worst - best) / best miss count over {LRU, PLRU, FIFO, RANDOM} at the same "
      "geometry. A policy matters only if the spread is large.\n")
    rows = []
    geoms = sorted({(s, a, l) for s, a, l, p in CFGS.values()
                    if sum(1 for q in CFGS.values() if q[:3] == (s, a, l)) >= 4})
    for g in geoms:
        for run in runs:
            ms = {CFGS[n][3]: stats(run, n)['miss'] for n in CFGS if CFGS[n][:3] == g}
            best, worst = min(ms.values()), max(ms.values())
            rows.append(("%dK %dw %dB" % (g[0] // KB, g[1], g[2]), NAME[run],
                         min(ms, key=ms.get), max(ms, key=ms.get),
                         "%.1f%%" % (100.0 * (worst - best) / best)))
    o.extend(table(rows, ("geometry", "workload", "best", "worst", "spread")))
    w("")

    # per-operator sensitivity at the CV-Wally default and a small cache
    w("## Per-operator behaviour (miss rate; X1 vs X1T)\n")
    for name in (BASE, "4K-4w-64B-plru", "32K-4w-64B-plru"):
        if name not in CFGS:
            continue
        w("### %s\n" % name)
        rows = []
        for k, kind in enumerate(META["op_kinds"]):
            if kind in ("CONV_2D", "FULLY_CONNECTED", "MAX_POOL_2D", "ADD"):
                row = [META["op_names"][k], kind]
                for r in [r for r in ('x1', 'x1t') if r in RUNS]:
                    s = stats(r, name, {k})
                    row.append("%.2f%% (%d)" % (s["rate"], s["miss"]))
                rows.append(row)
        o.extend(table(rows, ("op", "kind") + tuple(NAME[r] + " miss rate (misses)"
                                                    for r in ('x1', 'x1t') if r in RUNS)))
        w("")
    open(os.path.join(P, "cache_summary.md"), "w").write("\n".join(o) + "\n")
    figures(runs)
    print("\n".join(o[:60]))


def figures(runs):
    cols = {"b1": "tab:gray", "x1": "tab:blue", "x1t": "tab:red"}
    sty = lambda r: dict(marker="o", color=cols[r], label=NAME[r])
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
    for r in runs:
        ns = [n for n in CFGS if CFGS[n][1:] == (4, 64, 'plru')]
        ns.sort(key=lambda n: CFGS[n][0])
        ax[0].plot([CFGS[n][0] / KB for n in ns], [stats(r, n)["rate"] for n in ns], **sty(r))
        na = sorted([n for n in CFGS if CFGS[n][0] == 16 * KB and CFGS[n][2] == 64 and CFGS[n][3] == 'plru'],
                    key=lambda n: CFGS[n][1])
        ax[1].plot([CFGS[n][1] for n in na], [stats(r, n)["rate"] for n in na], **sty(r))
        nl = sorted([n for n in CFGS if CFGS[n][0] == 16 * KB and CFGS[n][1] == 4 and CFGS[n][3] == 'plru'],
                    key=lambda n: CFGS[n][2])
        ax[2].plot([CFGS[n][2] for n in nl], [stats(r, n)["rate"] for n in nl], **sty(r))
    for a, t, x in zip(ax, ("size (4-way, 64 B)", "associativity (16 KB, 64 B)",
                            "line size (16 KB, 4-way)"), ("KB", "ways", "bytes")):
        a.set_xscale("log", base=2)
        a.set_title(t, fontsize=10)
        a.set_xlabel(x)
        a.set_ylabel("D-cache miss rate (%)")
        a.grid(alpha=.3)
    ax[0].legend()
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "cache_geometry.png"), dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.2, 3.6))
    pols = ("lru", "plru", "fifo", "rand")
    sizes = (4, 8, 16, 32)
    wd = 0.2
    for j, pol in enumerate(pols):
        for i, r in enumerate([r for r in ('x1', 'x1t') if r in RUNS]):
            y = [stats(r, "%dK-4w-64B-%s" % (s, pol))["miss"] / stats(r, "%dK-4w-64B-plru" % s)["miss"]
                 for s in sizes]
            ax.bar([k + (j - 1.5) * wd + i * 4.6 for k in range(4)], y, wd,
                   color=plt.cm.tab10(j), label=pol if i == 0 else None)
    ax.set_xticks([k + i * 4.6 for i in range(2) for k in range(4)])
    ax.set_xticklabels(["%dK" % s for s in sizes] * 2, fontsize=8)
    ax.axhline(1, color="k", lw=.6)
    ax.set_ylabel("misses / PLRU misses")
    ax.set_title("replacement policy (4-way, 64 B): X1 | X1T", fontsize=10)
    ax.legend(ncol=4, fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "cache_policy.png"), dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
